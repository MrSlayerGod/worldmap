const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const coverage = {};
for (let plane = 0; plane < 4; plane++) {
    for (let zoom = 4; zoom <= 8; zoom++) {
        const directory = path.join(root, 'tiles/legacy667', String(plane), String(zoom));
        for (const x of fs.readdirSync(directory).sort((a, b) => a - b)) {
            const ys = fs.readdirSync(path.join(directory, x))
                .filter((name) => /^\d+\.png$/.test(name))
                .map((name) => Number(name.slice(0, -4))).sort((a, b) => a - b);
            coverage[`${plane}/${zoom}/${x}`] = ys;
        }
    }
}
fs.writeFileSync(path.join(root, 'js/legacy_tile_manifest.js'),
    '/* Generated by scripts/build_tile_manifest.cjs from the exported cache tiles. */\n' +
    'window.Legacy667TileCoverage = ' + JSON.stringify(coverage) + ';\n');
console.log('Indexed ' + Object.values(coverage).reduce((sum, ys) => sum + ys.length, 0) + ' native tiles.');
